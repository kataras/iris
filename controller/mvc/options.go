package mvc

import (
	"fmt"
	"reflect"

	"github.com/kataras/iris/v14/context"
	"github.com/kataras/iris/v14/controller/mvc/handler"
)

// Verb identifies one of the resource routes that `UseController` and
// `UseRepository` generate. It is the argument of the `Without` option.
type Verb uint8

// The generated resource routes, in registration order.
const (
	// Create is POST /resource.
	Create Verb = iota + 1
	// Get is GET /resource/{id}.
	Get
	// Update is PUT and PATCH /resource/{id}.
	Update
	// Delete is DELETE /resource/{id}.
	Delete
	// List is POST and QUERY /resource/list.
	List
)

// String returns the verb's name, for error messages and debugging.
func (v Verb) String() string {
	switch v {
	case Create:
		return "Create"
	case Get:
		return "Get"
	case Update:
		return "Update"
	case Delete:
		return "Delete"
	case List:
		return "List"
	default:
		return fmt.Sprintf("Verb(%d)", uint8(v))
	}
}

// isWrite reports whether the verb writes, so that `Guard` knows which
// routes it protects.
func (v Verb) isWrite() bool {
	return v == Create || v == Update || v == Delete
}

// Option customizes the routes generated by `UseController` and
// `UseRepository`. Options are plain functional options: pass as many as
// you need, they apply in order.
type Option func(*options)

// beforeWriteHook is a `BeforeWrite` hook with its model type erased. The
// concrete pointer is asserted back inside the closure that BeforeWrite
// builds, so a hook costs one type assertion and no reflection; "typ" is the
// *T it was declared for, kept so that a hook registered for the wrong model
// is caught when the routes are registered rather than silently skipped.
type beforeWriteHook struct {
	typ reflect.Type
	fn  func(ctx *context.Context, v any) error
}

type options struct {
	guards      []context.Handler
	without     [List + 1]bool
	idParamName string
	beforeWrite []beforeWriteHook
	pagination  []context.PaginationOption
}

// defaultOptions is the zero option set, used by the package-level option
// constructors to validate an argument against the shape of the value they
// will fill in.
var defaultOptions options

func makeOptions(opts []Option) *options {
	o := new(options)
	for _, opt := range opts {
		if opt == nil {
			continue
		}

		opt(o)
	}

	return o
}

// skip reports whether the route of the given verb must not be registered.
func (o *options) skip(v Verb) bool {
	return int(v) < len(o.without) && o.without[v]
}

// handlers returns the handler chain of a generated route: the guards, when
// the verb writes, followed by the route's own handler.
func (o *options) handlers(v Verb, h context.Handler) []context.Handler {
	if len(o.guards) == 0 || !v.isWrite() {
		return []context.Handler{h}
	}

	chain := make([]context.Handler, 0, len(o.guards)+1)
	chain = append(chain, o.guards...)
	return append(chain, h)
}

// runBeforeWrite runs the registered hooks in registration order over the
// decoded body. The first error stops the chain and is returned to the
// caller, which renders it through the rest/errors pipeline.
func (o *options) runBeforeWrite(ctx *context.Context, v any) error {
	for _, hook := range o.beforeWrite {
		if err := hook.fn(ctx, v); err != nil {
			return err
		}
	}

	return nil
}

// checkBeforeWrite panics when a hook was declared for another model than the
// one this resource writes. The hook would otherwise be skipped silently, and
// the thing it was skipping is typically "stamp the tenant id", so the
// failure would show up as a cross-tenant write and not as an error.
//
// It is a registration-time panic, like the one constructController raises
// for a bad type parameter: a mismatch here can only be a mistake in the
// program, never in a request.
func (o *options) checkBeforeWrite(caller, relPath string, want reflect.Type) {
	for _, hook := range o.beforeWrite {
		if hook.typ != want {
			panic(fmt.Sprintf("iris: mvc: %s: %s: mvc.BeforeWrite hook declared for %s, but this resource writes %s",
				caller, relPath, hook.typ, want))
		}
	}
}

// beforeWriteDecoder turns the registered hooks into a request decoder for
// the generated Create and Update handlers: it decodes the body the way the
// handler package would have, then hands the decoded value to the hooks. It
// returns nil, which the handler options skip, when no hook is registered,
// so a resource without hooks keeps the handler package's own decoder and
// pays nothing.
func beforeWriteDecoder[Request any](o *options) handler.Option {
	if len(o.beforeWrite) == 0 {
		return nil
	}

	decoder := handler.DefaultRequestDecoder[Request]()

	return handler.WithRequestDecoderFunc[Request](func(ctx *context.Context, req *Request) error {
		if decoder != nil {
			if err := decoder.DecodeRequest(ctx, req); err != nil {
				return err
			}
		}

		return o.runBeforeWrite(ctx, req)
	})
}

// Guard registers middleware for the write routes only: Create, Update and
// Delete. Reads (Get and List) stay as they were.
//
// It exists because "everyone may read, only a signed-in user may write" is
// the common shape, and a router-level Use cannot express it without
// splitting the resource into two routers.
//
//	mvc.UseRepository(repo, mvc.Guard(auth.VerifyHandler()))
func Guard(handlers ...context.Handler) Option {
	return func(o *options) {
		o.guards = append(o.guards, handlers...)
	}
}

// Without drops the generated routes of the given verbs. A dropped route is
// not registered at all, so a request to it answers 404, or 405 when the
// application enables FireMethodNotAllowed and another method of the same
// path remains.
//
// An unknown verb panics: it can only be a typo in the program.
//
//	mvc.UseRepository(repo, mvc.Without(mvc.Delete))
func Without(verbs ...Verb) Option {
	for _, verb := range verbs {
		if int(verb) <= 0 || int(verb) >= len(defaultOptions.without) {
			panic(fmt.Sprintf("iris: mvc: Without: unknown verb: %d", verb))
		}
	}

	return func(o *options) {
		for _, verb := range verbs {
			o.without[verb] = true
		}
	}
}

// IDParam overrides the path parameter name derived from the model type, so
// that /customers/{customer_id} can be registered as /customers/{id}. The
// macro (the ":uuid" in "{id:uuid}") still derives from the ID type.
func IDParam(name string) Option {
	if name == "" {
		panic("iris: mvc: IDParam: the parameter name is required")
	}

	return func(o *options) {
		o.idParamName = name
	}
}

// Pagination declares the list route's sort policy, the options
// Context.BindPagination and Context.Paginated take. A sort the policy does
// not allow answers 400 before the controller or the repository runs.
//
// A sort column reaches an ORDER BY clause, so the set of columns a client
// may name belongs to the endpoint and never to the request.
//
//	mvc.UseRepository(repo, mvc.Pagination(iris.AllowSort("created_at", "name")))
//	mvc.UseRepository(repo, mvc.Pagination(iris.DenySort("this list is ordered by rank")))
//
// The policy reads the decoded filter through its SortRequest method, which
// context.ListFilter provides, so a filter without one is unaffected.
func Pagination(opts ...context.PaginationOption) Option {
	return func(o *options) {
		o.pagination = append(o.pagination, opts...)
	}
}

// BeforeWrite registers a hook which runs on Create and on Update, after the
// request body is decoded and before the repository or the controller sees
// it. A non-nil error stops the request and renders through the rest/errors
// pipeline. Hooks run in registration order.
//
// It is how a value the client must not choose is stamped on every body: a
// tenant id, an owner, a created-by. The model type is a type parameter, so
// the hook receives *T directly and no reflection is involved at serve time.
// A hook whose T is not the type the resource writes panics when the routes
// are registered, naming both types.
//
//	mvc.BeforeWrite(func(ctx iris.Context, v *Invoice) error {
//		tenantID, ok := auth.ScopeID[string](ctx)
//		if !ok {
//			return errors.Unauthenticated
//		}
//		v.TenantID = tenantID
//		return nil
//	})
func BeforeWrite[T any](fn func(ctx *context.Context, v *T) error) Option {
	if fn == nil {
		return nil
	}

	return func(o *options) {
		o.beforeWrite = append(o.beforeWrite, beforeWriteHook{
			typ: reflect.TypeFor[*T](),
			fn: func(ctx *context.Context, v any) error {
				// checkBeforeWrite has already rejected a hook of another
				// model at registration, so this assertion holds.
				ptr, ok := v.(*T)
				if !ok {
					return nil
				}

				return fn(ctx, ptr)
			},
		})
	}
}
