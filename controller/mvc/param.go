type paramNameController interface {
	// ParamName should return the dynamic path parameter name, i.e. "id" for /users/{id}.
	// If empty or not implemented then the default is generated by the response structure's name.
	ParamName() string
}

func resolvePathParamName[T any]() string {
	var ctrlOrResp T
	if c, ok := any(ctrlOrResp).(paramNameController); ok {
		if paramName := c.ParamName(); paramName != "" {
			return paramName
		}
	}

	if reflex.IsStruct(ctrlOrResp) { // if it's a struct lookup the json fields for the id name.
		if fields, _ := reflex.LookupFieldsWithOptions(
			&reflex.LookupFieldsOptions{
				SkipUnexported: true,
				FieldTag:       "json",
				SkipField: func(field reflect.StructField) (bool, error) {
					return !strings.HasSuffix(reflex.SnakeCase(field.Name), "_id"), nil // make sure it's id and not a random word contains or ends with "id".
				},
			}, reflect.TypeOf(ctrlOrResp)); len(fields) > 0 {
			// get the first field that had the id inside and contains a json tag.
			idField, _, _ := strings.Cut(fields[0].Tag.Get("json"), ",") // get the name of the json field.
			paramName := reflex.ShortNameOf(ctrlOrResp) + "_" + idField  // get the short name of the type (e.g customer) + the id field name (e.g. id) = customer_id.
			return paramName
		}
	}

	paramName := reflex.ShortNameOf(ctrlOrResp) + "_id"
	return paramName
}

// resolvePathParamType returns the route macro that validates the controller's
// ID type. A string ID stays a plain string: declare the controller with
// uuid.UUID to get the uuid macro and its validation.
func resolvePathParamType[ID context.IDType]() string {
	var id ID
	switch any(id).(type) {
	case int:
		return "int"
	case int64:
		return "int64"
	case uint64:
		return "uint64"
	case uuid.UUID:
		return "uuid"
	default:
		return "string"
	}
}
