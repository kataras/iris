// controllerParamNameMap is a map of the controller's pointer to its path
// parameter. The typed controller pointer itself is the key: it keeps the
// controller reachable and its identity stable across the app's lifetime.
var (
	controllerParamMu      sync.RWMutex
	controllerParamNameMap = make(map[any]*RawPathParam)
)

// storePathParam stores the path parameter of the controller.
func storePathParam(ctrl any, p *RawPathParam) {
	controllerParamMu.Lock()
	controllerParamNameMap[ctrl] = p
	controllerParamMu.Unlock()
}

// GetPathParam returns the path parameter of the controller.
func GetPathParam[T any](ctrl *T) *RawPathParam {
	controllerParamMu.RLock()
	p := controllerParamNameMap[any(ctrl)]
	controllerParamMu.RUnlock()
	return p
}

// RawPathParam holds the generated path parameter's name and type.
type RawPathParam struct {
	Name      string
	Type      string
	RoutePath string
}

func newRawPathParam[Response any, ID context.IDType]() *RawPathParam {
	paramName := resolvePathParamName[Response]() // customer_id
	paramType := resolvePathParamType[ID]()       // uuid
	return newNamedPathParam(paramName, paramType)
}

// newNamedPathParam builds a path parameter of an explicit name, for the
// IDParam option: the macro still comes from the ID type, only the name the
// route and the client see is the caller's.
func newNamedPathParam(paramName, paramType string) *RawPathParam {
	detailPath := fmt.Sprintf("/{%s:%s}", paramName, paramType) // /{customer_id:uuid}
	return &RawPathParam{Name: paramName, Type: paramType, RoutePath: detailPath}
}

// A 2nd level of abstraction for the path parameter,
// in order to be registered and resolved-later-on as a different dependency
// for each type.

// PathParam is a dynamic typed path parameter which can be used
// as a dependency to the controller's fields to the response type the path parameter belongs to.
// T is the Response type and V is the ID type (string, int, int64, uint64 or uuid.UUID).
type PathParam[T any, V context.IDType] struct {
	*RawPathParam
}

// Get returns the path parameter's actual value from the context.
//
// It never panics: a request must not be able to crash the server through
// a parameter type it controls. When the stored value is already a V the
// cost is a single type assertion, exactly as before. Only on a type
// mismatch (the uuid macro stores a uuid.UUID while V is string, or an
// untyped "{id}" stores a string while V is uuid.UUID, for example) the value
// is converted into V; if that fails too, the zero V is returned.
func (p *PathParam[T, V]) Get(ctx *context.Context) V {
	value, _ := handler.ConvertPathParamValue[V](ctx.Params().Get(p.Name))
	return value
}

// GetString returns the path parameter's value as string from the context.
func (p *PathParam[T, V]) GetString(ctx *context.Context) string {
	return ctx.Params().GetString(p.Name)
}

