var (
	// ErrClientTokenMissing is returned when the token does not contain any oauth2 client claims.
	ErrClientTokenMissing = fmt.Errorf("client token claims: %w", jwt.ErrMissing)
	// ErrClientInsufficientScopes is returned when the client does not have the required scopes.
	ErrClientInsufficientScopes = fmt.Errorf("client has insufficient scopes")
)

const clientClaimsContextKey = "iris.auth.oauth2.client_claims"

// GetClientClaims returns the token's claims of the OAuth2 client that is making the request.
func GetClientClaims(ctx *context.Context) (ClientTokenClaims, error) {
	if clientClaims, ok := ctx.ValueAs[ClientTokenClaims](clientClaimsContextKey); ok {
		return clientClaims, nil
	}

	// As an extra step, let's check if the ClientTokenClaims itself is registered to the context by the auth middleware.
	// If so, return them.
	if clientClaims := auth.GetUser[ClientTokenClaims](ctx); clientClaims.ClientID != "" {
		return clientClaims, nil
	}

	// if client, ok := GetClient(ctx); ok {
	// 	return client.Claims(client.Scopes), nil
	// }

	token, ok := auth.GetToken(ctx) // the verified access token after Auth#VerifyHandler executed.
	if !ok {
		return ClientTokenClaims{}, jwt.ErrMissing
	}

	// The token is carrying the client_id claim
	// (embedded automatically by the oauth2 server upon token creation).
	aud := token.StandardClaims.Audience.String()
	if aud == "" {
		// We are sure it doesn't contain any oauth2 claim.
		// So the user is authenticated directly to the application.
		return ClientTokenClaims{}, fmt.Errorf("%w: no audience", ErrClientTokenMissing)
	}

	// Extract any of the oauth2 client claims.
	var clientClaims ClientTokenClaims
	if err := json.Unmarshal(token.Payload, &clientClaims); err != nil {
		return ClientTokenClaims{}, fmt.Errorf("%w: %w", ErrClientTokenMissing, err)
	}

	// A minor case is that the aud may not be empty but set
	// by custom claims, so we need to check if it's actually the client_id.
	hasClient := clientClaims.ClientID != ""
	if !hasClient {
		return ClientTokenClaims{}, ErrClientTokenMissing
	}

	// We are sure that the token is generated by the oauth2 server.
	// Check if the client_id is the same as the token's audience.
	if clientClaims.ClientID != aud {
		return clientClaims, ErrClientMismatch
	}

	// Note that we don't set the clientClaimsContextKey here.
	// See AllowScopes, so we only set it once on matched scopes.

	return clientClaims, nil
}

// AllowPolicies returns a middleware that validates an OAuth2 client's access token
// for a given resource (and action). E.g. "users:read" (as ResourcePolicy{"users", "read"}),
// "users:*" or even "users".
//
// Storing Policy-Like Scopes on the OAuth2 Client
// When registering a client, you can define resource-based scopes, e.g.:
//
//	client, err := oauth2Server.RegisterClient(ctx, oauth2.ClientRegistration{
//		Name:            "ExampleClient",
//		Website:         "https://example.com",
//		LogoURL:         "https://example.com/logo.png",
//		RedirectURI:     "https://localhost:8081/callback",
//		VerificationURI: "...device_verification...",
//		GrantTypes:      []string{"authorization_code", "refresh_token"},
//		Scopes:          []string{"users:read", "users:write", "orders:read", "orders:write"}, // resource-based scopes
//		CodeMaxAge:      3600,
//		AccessMaxAge:    3600,
//		RefreshMaxAge:   604800,
//	})
//
// Usage:
//
//	app.Post("/",
//		AuthInstance.VerifyHandler(),
//		oauth2.AllowPolicies(oauth2.ResourcePolicy{Resource: "users", Action: "write"}),
//		createUserHandler)
func AllowPolicies(policies ...Policy) context.Handler {
	return checkPolicies(true, policies...)
}

// DisallowPolicies returns a middleware that ensures an OAuth2 client's access token
// does not contain any of the specified resource policies. If the token contains any of the
// disallowed policies, the request is halted.
func DisallowPolicies(policies ...Policy) context.Handler {
	return checkPolicies(false, policies...)
}

// AllowScopes returns a middleware that validates an OAuth2 client's access token.
// If the token is invalid or the client does not exist, the request is halted.
//
// This middleware handles two scenarios:
//  1. Direct application sign-in: The token does not carry OAuth2 client data,
//     so all resources are accessible without scope checks.
//  2. OAuth2 client sign-in: The token embeds the client_id and scopes,
//     which are validated to ensure the client has the necessary permissions.
//
// Usage:
//
//	admin := app.Router("/admin", AuthInstance.VerifyHandler(), oauth2.AllowScopes("users:read", "users:write"))
//	admin.Get("/restricted", mainHandler)
func AllowScopes(requiredScopes ...string) context.Handler {
	policies := NewScopePolicies(requiredScopes...)
	return AllowPolicies(policies...)
}

// DisallowScopes returns a middleware that ensures an OAuth2 client's access token
// does not contain any of the specified scopes. If the token contains any of the
// disallowed scopes, the request is halted.
func DisallowScopes(disallowedScopes ...string) context.Handler {
	policies := NewScopePolicies(disallowedScopes...)
	return DisallowPolicies(policies...)
}

// The allow flag determines whether the function checks for allowed or disallowed policies.
// If allow is true, the function ensures the token's scopes satisfy at least one of the required policies.
// If allow is false, the function ensures the token's does not satisfy any of the disallowed policies.
func checkPolicies(allow bool, policies ...Policy) context.Handler {
	if len(policies) == 0 {
		return nil
	}

	return func(ctx *context.Context) {
		var clientClaims ClientTokenClaims

		// If the full client is registered in the request, then use it to extract the claims directly,
		// so the checkPolicies can work on the actual client (see ClientVerifier).
		if client, ok := GetClient(ctx); ok {
			clientClaims = client.Claims(client.Scopes)
			clientClaims.ClientSecret = client.Secret // if exists, set it.
		} else {
			var err error
			clientClaims, err = GetClientClaims(ctx)
			if err != nil {
				if errors.Is(err, ErrClientTokenMissing) {
					if auth.UserAuthorized(ctx) {
						// The user is authenticated directly to the application.
						ctx.Next()
						return
					}
				}

				// Private: why a token was not accepted is not for the caller
				// to read. The client gets the 401, the error stays readable
				// through ctx.GetErr.
				ctx.StopWithPlainError(401, context.PrivateError(err))
				return
			}
		}

		// Here we could get the client from the store
		// on each request and check if the client exists and allows the token's scopes.
		// But we don't need to do it as the token expires so on refreshes this will be handled.
		//  Retrieve the OAuth2 client from the server's client store.
		// client, ok, err := server.ClientStore.GetClient(ctx, clientClaims.ClientID)
		// if err != nil || !ok {
		// 	ctx.StopWithError(iris.StatusBadRequest, err)
		// 	return
		// }
		// Check if the client's scopes contain all required.
		// if !clientMatchScopes(client, requiredScopes) {
		// 	ctx.StopWithStatus(iris.StatusForbidden)
		// 	return
		// }
		// ctx.Values().Set(clientContextKey, client)

		matched := matchPolicies(ctx, &clientClaims, policies)
		if (allow && !matched) || (!allow && matched) {
			ctx.StopWithPlainError(403, ErrClientInsufficientScopes)
			return
		}

		// Set the client claims to the context.
		ctx.Values().Set(clientClaimsContextKey, clientClaims)
		ctx.Next()
	}
}
