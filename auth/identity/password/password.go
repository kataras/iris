package password

import (
	"crypto/aes"
	"crypto/cipher"
	"crypto/rand"
	"encoding/base64"
	"encoding/hex"
	"errors"

	"golang.org/x/crypto/bcrypt"
)

// GenerateSharedKey returns a hex-encoded, cryptographically random 16-byte key
// (128-bit AES key).
// This is convenient for returning as JSON in an HTTP response.
func GenerateSharedKey() (string, error) {
	key, err := generateRandomBytes(16)
	if err != nil {
		return "", err
	}
	return hex.EncodeToString(key), nil
}

// Decrypt decrypts a hex-encoded AES-GCM ciphertext back to its plaintext using a shared key.
// The shared key must be hex-encoded, as generated by the "GenerateSharedKey" function.
func Decrypt(cipherHex string, sharedKeyHex string) (string, error) {
	decodedSharedKey, err := hex.DecodeString(sharedKeyHex)
	if err != nil {
		return "", err
	}

	return decrypt(cipherHex, decodedSharedKey)
}

// decrypt decrypts ciphertext to recover the plaintext data (e.g. password sent by the client-side which is encrypted for maxiumum security, even on HTTPS).
// See sdk/password.go for the EncryptPassword function.
func decrypt(cipherHex string, sharedKey []byte) (string, error) {
	// data, err := base64.StdEncoding.DecodeString(cipherB64)
	// Use hex instead of base64, as the url query parameters may not be able to handle base64.
	data, err := hex.DecodeString(cipherHex)
	if err != nil {
		return "", err
	}

	block, err := aes.NewCipher(sharedKey)
	if err != nil {
		return "", err
	}
	gcm, err := cipher.NewGCM(block)
	if err != nil {
		return "", err
	}

	if len(data) < gcm.NonceSize() {
		return "", errors.New("invalid data length")
	}
	nonce, ciphertext := data[:gcm.NonceSize()], data[gcm.NonceSize():]

	plaintext, err := gcm.Open(nil, nonce, ciphertext, nil)
	if err != nil {
		return "", err
	}
	return string(plaintext), nil
}

// IsHexEncoded checks if the given string is a valid hex-encoded string
// which could indicate an AES-encrypted password from the client-side SDK.
func IsHexEncoded(s string) bool {
	if len(s) == 0 || len(s)%2 != 0 {
		return false
	}

	for _, char := range s {
		if !((char >= '0' && char <= '9') || (char >= 'a' && char <= 'f') || (char >= 'A' && char <= 'F')) {
			return false
		}
	}

	// Additional heuristic: AES-GCM encrypted passwords are typically longer than 32 chars
	// (12 bytes nonce + at least 8 bytes password = 20 bytes = 40 hex chars minimum)
	return len(s) >= 40
}

// IsHashed checks if the given string is a valid bcrypt hash.
// Bcrypt hashes have a specific format: $2a$cost$salthash, $2b$cost$salthash or $2y$cost$salthash
// They are exactly 60 characters long and start with $2a$, $2b$ or $2y$
func IsHashed(password string) bool {
	// Bcrypt hashes are exactly 60 characters long
	if len(password) != 60 {
		return false
	}

	// Bcrypt hashes start with $2a$, $2b$ or $2y$ followed by cost (2 digits) and $
	// Example: $2a$10$N9qo8uLOickgx2ZMRZoMye or $2b$12$DMRH1OW.../
	if len(password) < 7 {
		return false
	}

	// Check for bcrypt prefix patterns
	return (password[:4] == "$2a$" || password[:4] == "$2b$" || password[:4] == "$2y$") &&
		password[6] == '$' // Cost separator
}

// Cost is the bcrypt cost used by HashPassword.
// 12 is above bcrypt.DefaultCost (10). Hashes created at another cost stay verifiable.
// Bcrypt uses only the first 72 bytes of a password.
var Cost = 12

// HashPassword hashes the given plaintext password using bcrypt with the package
// level Cost.
// Bcrypt automatically incorporates the salt inside the hashed output.
// We only store the hashed string returned by Bcrypt – no separate salt needed.
// Max password limit is 72 bytes.
// A typical bcrypt hash encoded in ASCII is 60 characters long, which includes the cost, salt, and checksum.
func HashPassword(plainPassword string) (string, error) {
	hashed, err := bcrypt.GenerateFromPassword([]byte(plainPassword), Cost)
	if err != nil {
		return "", err
	}
	return string(hashed), nil
}

// ComparePassword compares the plaintext password with its hashed counterpart.
func ComparePassword(hashedPassword, plainPassword string) bool {
	err := bcrypt.CompareHashAndPassword([]byte(hashedPassword), []byte(plainPassword))
	return err == nil
}

// GenerateSalt returns a base64-encoded random 16-byte salt.
// A commonly recommended size is 16 bytes for adequate security while minimizing overhead.
func GenerateSalt() ([]byte, error) {
	salt, err := generateRandomBytes(16)
	if err != nil {
		return nil, err
	}

	buf := make([]byte, base64.StdEncoding.EncodedLen(len(salt)))
	base64.StdEncoding.Encode(buf, salt)
	return buf, nil
}

func generateRandomBytes(size int) ([]byte, error) {
	salt := make([]byte, size) // 16 byte length generates 128-bit AES key.
	if _, err := rand.Read(salt); err != nil {
		return nil, err
	}

	// skip the base64 step.
	return salt, nil
}

// GenerateRandomPassword generates a strong random password meeting the specified criteria:
// - At least 8 characters long
// - Contains at least one uppercase letter
// - Contains at least one lowercase letter
// - Contains at least one number
// - Contains at least one symbol
func GenerateRandomPassword(length int) (string, error) {
	if length < 8 {
		length = 8 // Ensure minimum length
	}

	const (
		uppercase = "ABCDEFGHIJKLMNOPQRSTUVWXYZ"
		lowercase = "abcdefghijklmnopqrstuvwxyz"
		numbers   = "0123456789"
		symbols   = "!@#$%^&*()-_=+[]{}|;:,.<>?"
		allChars  = uppercase + lowercase + numbers + symbols
	)

	// Ensure we have at least one character from each required category
	password := make([]byte, length)

	// Generate one character from each required category
	categories := []string{uppercase, lowercase, numbers, symbols}
	for i, category := range categories {
		randomIndex, err := generateSecureRandomInt(len(category))
		if err != nil {
			return "", err
		}
		password[i] = category[randomIndex]
	}

	// Fill the remaining positions with random characters from all categories
	for i := len(categories); i < length; i++ {
		randomIndex, err := generateSecureRandomInt(len(allChars))
		if err != nil {
			return "", err
		}
		password[i] = allChars[randomIndex]
	}

	// Shuffle the password to avoid predictable patterns
	for i := len(password) - 1; i > 0; i-- {
		j, err := generateSecureRandomInt(i + 1)
		if err != nil {
			return "", err
		}
		password[i], password[j] = password[j], password[i]
	}

	return string(password), nil
}

// generateSecureRandomInt generates a cryptographically secure random integer between 0 and max-1
func generateSecureRandomInt(max int) (int, error) {
	if max <= 0 {
		return 0, errors.New("max must be positive")
	}

	randomBytes := make([]byte, 4)
	_, err := rand.Read(randomBytes)
	if err != nil {
		return 0, err
	}

	// Convert bytes to uint32 and take modulo
	randomInt := uint32(randomBytes[0])<<24 | uint32(randomBytes[1])<<16 | uint32(randomBytes[2])<<8 | uint32(randomBytes[3])
	return int(randomInt) % max, nil
}
